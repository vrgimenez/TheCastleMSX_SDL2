/*
 * THE CASTLE — Cargador de tiles (reescrito)
 * ==========================================
 * CORRECCIONES vs versión anterior:
 *
 * BUG 1 — Formato del bloque
 *   Anterior: block = array de N punteros de 2 bytes (uno por tile)
 *   Correcto: block = UN puntero de 2 bytes → datos contiguos N×16 bytes
 *   sub_64AB lee UN puntero del bloque; sub_6CD9 avanza DE en 16 bytes/tile.
 *
 * BUG 2 — Conteo de tiles (B "enhebrado")
 *   sub_64AB hace PUSH BC / POP BC → B se RESTAURA en cada llamada.
 *   Entre llamadas sin LD B intermedio, B vale lo de la llamada anterior.
 *   Mapa VRAM correcto:
 *     0x0D        DOOR     (B=1)
 *     0x0E..0x29  BG3      (B=28, fuente: BIOS)
 *     0x2A..0x45  BG0      (B=28, B restaurado del anterior)
 *     0x46        KEY      (B=1)
 *     0x47..0x50  ANIM_BG  (B=10)
 *     0x51..0x54  BG4_A    (B=4)
 *     0x55..0x56  BG4_B    (B=2)
 *     0x57..0x58  BG4_C    (B=2)
 *     0x59..0x72  WALLS    (B=26, fuente: BIOS)
 *
 * BUG 3 — Tiles desde BIOS ROM
 *   BG3   src=0xF40A → RAM MSX post-INITXT (charset del BIOS)
 *   WALLS src=0x3110 → BIOS ROM página 1
 *   Solución: charset MSX1 embebido (datos estándar, idénticos en todos los MSX1).
 *
 * BUG 4 — sub_6CD9 preserva HL con PUSH/POP
 *   HL es el índice de fila (0-7), NO acumula la base.
 *   Cada escritura: PUSH HL; ADD HL,base; WRTVRM; POP HL; INC HL
 */

