static uint8_t read_src(uint32_t abs_addr, uint32_t tile_byte_offset)
{
    uint32_t addr = abs_addr + tile_byte_offset;

    /* Game ROM (0x4000-0xBFFF, 32KB) */
    if (addr >= (uint32_t)ROM_ORG && addr < (uint32_t)(ROM_ORG + g_rom_size))
        return g_rom[addr - ROM_ORG];

    /* BIOS ROM externo (0x0000-0x7FFF) */
    if (s_bios_size > 0 && addr < (uint32_t)s_bios_size)
        return s_bios[addr];

    /* Fallback: tiles sinteticos — se selecciona según el rango de la dirección
     * en el espacio MSX: usamos byte_offset para indexar en el tile correcto.
     * abs_addr distingue entre BG3 (0xF40A) y WALLS (0x3110). */
    if (abs_addr >= 0xC000u) {
        /* BG3 (src=0xF40A): tile_byte_offset 0..447 → tile i = off/16, byte = off%16 */
        uint32_t tile_i    = tile_byte_offset / 16u;
        uint32_t byte_in_t = tile_byte_offset % 16u;
        if (tile_i < 28u)
            return SYNTH_BG3[tile_i][byte_in_t];
        return 0x00u;
    } else {
        /* WALLS (src=0x3110): tile_byte_offset 0..415 */
        uint32_t tile_i    = tile_byte_offset / 16u;
        uint32_t byte_in_t = tile_byte_offset % 16u;
        if (tile_i < 28u)
            return SYNTH_WALLS[tile_i][byte_in_t];
        return 0x00u;
    }
}

/* ==========================================================================
 * sub_6CD9 — Escribir un tile de 16 bytes a VRAM
 *
 * Formato fuente: (pat0,col0, pat1,col1, ..., pat7,col7) — interleaved.
 * sub_6CD9 preserva HL con PUSH/POP: HL = solo el índice de fila (0-7).
 * Cada iteración: PUSH HL; ADD HL,base; WRTVRM(A); POP HL; INC HL.
 *
 * third = 0,1,2 para un tercio específico; -1 para los tres.
 * ========================================================================== */
static void write_tile_to_vram(uint32_t src_ptr, uint8_t tile_idx, int third)
{
    int t0 = (third < 0) ? 0 : third;
    int t1 = (third < 0) ? 3 : third + 1;

    for (int t = t0; t < t1; t++) {
        uint16_t pat = (uint16_t)(VRAM_PAT_BASE
                       + (uint16_t)t * VRAM_THIRD_SIZE
                       + (uint16_t)tile_idx * 8u);
        uint16_t col = (uint16_t)(VRAM_COL_BASE
                       + (uint16_t)t * VRAM_THIRD_SIZE
                       + (uint16_t)tile_idx * 8u);
        for (uint8_t r = 0u; r < 8u; r++) {
            hal_vdp_write_vram((uint16_t)(pat + r), read_src(src_ptr, r*2u));
            hal_vdp_write_vram((uint16_t)(col + r), read_src(src_ptr, r*2u+1u));
        }
    }
}

/* ==========================================================================
 * sub_64AB — Cargar N tiles desde un bloque descriptor
 *
 * El bloque (en ROM, apuntado por desc_addr) tiene:
 *   [0..1] = UN puntero de 2 bytes al inicio de los datos contiguos
 *
 * Los datos = count × 16 bytes a partir de ese puntero.
 * sub_6CD9 avanza DE en 16 bytes por tile (INC DE × 2 × 8 filas).
 *
 * block_extra_offset: cuántos bytes avanzar en el bloque antes de leer
 * el puntero (para BG4_B y BG4_C que comparten bloque pero usan
 * el puntero siguiente: sub_64AB avanza HL en 2 bytes por llamada,
 * y el bloque contiene múltiples punteros de 2 bytes).
 * ========================================================================== */
static void load_tileset_impl(uint16_t desc_addr, uint16_t block_extra,
                               uint8_t vram_start, uint8_t count,
                               bool all_thirds)
{
    /* Nivel 1: leer la dirección del bloque de datos */
    uint16_t block_addr = rom_rw(desc_addr);
    /* Nivel 2: leer el puntero a los datos desde el bloque */
    uint16_t data_ptr_word = rom_rw((uint16_t)(block_addr + block_extra));
    uint32_t src_ptr = (uint32_t)data_ptr_word;

    for (uint8_t i = 0u; i < count; i++) {
        write_tile_to_vram(src_ptr + (uint32_t)i * 16u,
                           (uint8_t)(vram_start + i),
                           all_thirds ? -1 : 0);
    }
}

/* Helpers públicos */
static void load_tileset(uint16_t desc, uint8_t vram_start,
                         uint8_t count, bool all_thirds)
{
    load_tileset_impl(desc, 0u, vram_start, count, all_thirds);
}

/* ==========================================================================
 * tiles_load_from_rom() — Carga inicial completa (sub_4D52 → sub_4E0F)
 * ========================================================================== */
void tiles_load_from_rom(const uint8_t *rom_data, uint32_t rom_size)
{
    g_rom      = rom_data;
    g_rom_size = rom_size;

    /* Limpiar VRAM pattern + color + name */
    hal_vdp_fill_vram(VRAM_PAT_BASE,  0x00u, 0x1800u);
    hal_vdp_fill_vram(VRAM_COL_BASE,  0x00u, 0x1800u);
    hal_vdp_fill_vram(VRAM_NAME_BASE, 0x00u, 768u);

    /* Secuencia exacta de sub_4D52 con B threading: */
    load_tileset(BLOCK_DOOR,    IDX_DOOR,    1u,  true);   /* B=1  */
    load_tileset(BLOCK_BG3,     IDX_BG3,     28u, true);   /* B=28 */
    load_tileset(BLOCK_BG0,     IDX_BG0,     28u, true);   /* B=28 (restaurado) */
    load_tileset(BLOCK_KEY,     IDX_KEY,     1u,  true);   /* B=1  */
    load_tileset(BLOCK_ANIM_BG, IDX_ANIM_BG, 10u, true);   /* B=10 */
    load_tileset(BLOCK_BG4,     IDX_BG4_A,   4u,  true);   /* B=4  */
    /* BG4_B y BG4_C: mismo bloque BLOCK_BG4 pero HL avanzado en 2 y 4 bytes */
    load_tileset_impl(BLOCK_BG4, 2u, IDX_BG4_B, 2u, true); /* B=2 */
    load_tileset_impl(BLOCK_BG4, 4u, IDX_BG4_C, 2u, true); /* B=2 */
    load_tileset(BLOCK_WALLS,   IDX_WALLS,   26u, true);   /* B=26 */

    /* sub_4E8E: recarga final WALLS(28) + ANIM_BG(10) */
    tiles_reload_walls_and_anim();
}

/* ==========================================================================
 * tiles_reload_walls_and_anim() — Recargar entre salas (sub_4E8E)
 * sub_4E8E: WALLS B=0x1C (28) + ANIM_BG B=0x0A (10)
 * ========================================================================== */
void tiles_reload_walls_and_anim(void)
{
    load_tileset(BLOCK_WALLS,   IDX_WALLS,   28u, true);
    load_tileset(BLOCK_ANIM_BG, IDX_ANIM_BG, 10u, true);
}

/* ==========================================================================
 * tiles_animate() — Rotar tile animado cada 4 frames
 * ========================================================================== */
void tiles_animate(uint8_t frame_counter)
{
    if ((frame_counter & 0x03u) != 0u) return;
    uint8_t  slot    = (uint8_t)((frame_counter >> 2u) % 10u);
    uint8_t  next_s  = (uint8_t)((slot + 1u) % 10u);
    uint16_t blk     = rom_rw(BLOCK_ANIM_BG);
    uint32_t src     = (uint32_t)rom_rw(blk);
    write_tile_to_vram(src + (uint32_t)next_s * 16u,
                       (uint8_t)(IDX_ANIM_BG + slot), -1);
}

